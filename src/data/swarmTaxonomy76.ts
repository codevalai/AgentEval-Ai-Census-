// Helper for exact integer distribution (Hare-Niemeyer Largest Remainder) across all 76 domains
function distributeTaxonomyExact(baseValues: number[], targetTotal: number): number[] {
  const baseSum = baseValues.reduce((a, b) => a + b, 0);
  if (baseSum <= 0) return [...baseValues];
  const exactQuotas = baseValues.map((val) => (val / baseSum) * targetTotal);
  const integerParts = exactQuotas.map((q) => Math.floor(q));
  const currentSum = integerParts.reduce((a, b) => a + b, 0);
  const remainderCount = Math.max(0, Math.round(targetTotal - currentSum));

  const remainders = exactQuotas.map((q, idx) => ({
    idx,
    rem: q - integerParts[idx],
  }));
  remainders.sort((a, b) => b.rem - a.rem);

  for (let i = 0; i < remainderCount && i < remainders.length; i++) {
    integerParts[remainders[i].idx] += 1;
  }
  return integerParts;
}

// Mathematically reconcile all 76 domains at initialization so:
// 1. Sum(estimatedAgents) === 814,373.0M (814.37B Combined Active+Latent, matching 2024-2026 Timeline & 11-Row Country Table)
// 2. Sum(verifiedAgents) === 342,892,410,000 (342.89B Active Concurrent Agents Worldwide)
(() => {
  const TARGET_MACRO_MIL = 814373.0;
  const TARGET_VERIFIED = 342892410000;
  const rawWeights = SWARM_TAXONOMY_DOMAINS.map((d) => d.estimatedAgents);
  const rawSum = rawWeights.reduce((acc, w) => acc + w, 0);
  const exactVerified = distributeTaxonomyExact(rawWeights, TARGET_VERIFIED);

  let runningMacro = 0;
  SWARM_TAXONOMY_DOMAINS.forEach((d, idx) => {
    const share = rawWeights[idx] / rawSum;
    if (idx < SWARM_TAXONOMY_DOMAINS.length - 1) {
      const scaledMacro = parseFloat((share * TARGET_MACRO_MIL).toFixed(1));
      d.estimatedAgents = scaledMacro;
      runningMacro += scaledMacro;
    } else {
      d.estimatedAgents = parseFloat((TARGET_MACRO_MIL - runningMacro).toFixed(1));
    }
    d.verifiedAgents = exactVerified[idx];
  });
})();

// Helper to calculate total taxonomy metrics (supports live dynamic activeAgentsTotal with zero drift across all 76 cards)
export function getTaxonomySummary(
  liveActiveAgents: number = 342892410000,
  liveCombinedAgents?: number
) {
  const totalDomains = SWARM_TAXONOMY_DOMAINS.length;
  const activeDelta = Math.max(0, Math.round(liveActiveAgents - 342892410000));
  const latentDelta = Math.round(activeDelta * 1.375);
  const combinedTotal =
    typeof liveCombinedAgents === 'number'
      ? liveCombinedAgents
      : 814373000000 + activeDelta + latentDelta;
  const liveCombinedMil = parseFloat((combinedTotal / 1e6).toFixed(1));

  const baseVerified = SWARM_TAXONOMY_DOMAINS.map((d) => d.verifiedAgents || 0);
  const liveVerifiedPerDomain = distributeTaxonomyExact(baseVerified, liveActiveAgents);

  const rawMacro = SWARM_TAXONOMY_DOMAINS.map((d) => d.estimatedAgents);
  const rawMacroSum = rawMacro.reduce((a, b) => a + b, 0);
  let runningMacroMil = 0;

  const domains: SwarmTaxonomyDomain[] = SWARM_TAXONOMY_DOMAINS.map((d, idx) => {
    let estMil: number;
    if (idx < SWARM_TAXONOMY_DOMAINS.length - 1) {
      estMil = parseFloat(((rawMacro[idx] / rawMacroSum) * liveCombinedMil).toFixed(1));
      runningMacroMil += estMil;
    } else {
      estMil = parseFloat((liveCombinedMil - runningMacroMil).toFixed(1));
    }
    return {
      ...d,
      verifiedAgents: liveVerifiedPerDomain[idx],
      estimatedAgents: estMil,
    };
  });

  const totalGrowthRate = domains.reduce((acc, d) => acc + d.growthRatePerSec, 0);

  const byLayer = SWARM_TAXONOMY_LAYERS.map((layer) => {
    const layerDomains = domains.filter((d) => d.layer === layer.id);
    const layerAgents = parseFloat(layerDomains.reduce((acc, d) => acc + d.estimatedAgents, 0).toFixed(1));
    const layerVerified = layerDomains.reduce((acc, d) => acc + (d.verifiedAgents || 0), 0);
    const layerGrowth = parseFloat(layerDomains.reduce((acc, d) => acc + d.growthRatePerSec, 0).toFixed(1));
    return {
      ...layer,
      domainCount: layerDomains.length,
      estimatedAgentsMil: layerAgents,
      verifiedAgentsCount: layerVerified,
      growthRatePerSec: layerGrowth,
    };
  });

  return {
    totalDomains,
    totalAgentsMil: liveCombinedMil,
    verifiedTotalUnits: liveActiveAgents,
    totalGrowthRate: parseFloat(totalGrowthRate.toFixed(1)),
    domains,
    byLayer,
  };
}


